import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { mkdir, readFile, rm } from 'node:fs/promises';
import { resolve, join, sep } from 'node:path';
import { randomUUID } from 'node:crypto';
const root = resolve('.');
const runtimeRoot = join(root, '.runtime');
const fixture = resolve(runtimeRoot, 'desktop-test-' + randomUUID());
assert.ok(fixture.startsWith(runtimeRoot + sep));
await mkdir(fixture, { recursive: true });
const executable = process.argv[2] ? resolve(process.argv[2]) : join(root, '.tools/electron/electron.exe');
const args = process.argv[2] ? ['--lifecycle-test'] : [join(root, 'desktop'), '--lifecycle-test'];
const env = { ...process.env, SPAM_DESKTOP_TEST_DIR: fixture };
delete env.ELECTRON_RUN_AS_NODE;
const child = spawn(executable, args, { env, windowsHide: true, stdio: ['ignore', 'pipe', 'pipe'] });
let errors = ''; child.stderr.on('data', data => { errors += data.toString(); });
const timeout = setTimeout(() => child.kill(), 45000);
const code = await new Promise((resolveExit, reject) => { child.once('error', reject); child.once('exit', resolveExit); });
clearTimeout(timeout);
assert.equal(code, 0, errors);
const report = JSON.parse(await readFile(join(fixture, 'lifecycle-report.json'), 'utf8'));
assert.equal(report.loaded, true);
assert.equal(report.windowClosed, true);
assert.equal(report.serverClosed, true);
await assert.rejects(fetch(`http://127.0.0.1:${report.port}/health`, { signal: AbortSignal.timeout(1000) }));
const isAlive = pid => { try { process.kill(pid, 0); return true; } catch { return false; } };
for (let attempt = 0; attempt < 20 && report.ownedProcessIds.some(isAlive); attempt++) await new Promise(resolveWait => setTimeout(resolveWait, 100));
assert.deepEqual(report.ownedProcessIds.filter(isAlive), [], 'Desktop process still alive after closing the window.');
console.log('PASS: real desktop window loaded; closing it stopped the API and every Electron process reported by the app.');
await rm(fixture, { recursive: true });
const quitFixture = fixture + '-quit';
assert.ok(quitFixture.startsWith(runtimeRoot + sep));
await mkdir(quitFixture, { recursive: true });
const quitEnv = { ...env, SPAM_DESKTOP_TEST_DIR: quitFixture };
const primary = spawn(executable, [...args, '--lifecycle-hold'], { env: quitEnv, windowsHide: true, stdio: 'ignore' });
const primaryExit = new Promise((resolveExit, reject) => { primary.once('error', reject); primary.once('exit', resolveExit); });
let ready;
for (let attempt = 0; attempt < 150; attempt++) {
  try { ready = JSON.parse(await readFile(join(quitFixture, 'lifecycle-ready.json'), 'utf8')); break; } catch {}
  await new Promise(resolveWait => setTimeout(resolveWait, 100));
}
assert.ok(ready?.loaded, 'Desktop did not become ready.');
const invokeSecond = extra => new Promise((resolveExit, reject) => {
  const second = spawn(executable, [...args, ...extra], { env: quitEnv, windowsHide: true, stdio: 'ignore' });
  second.once('error', reject); second.once('exit', resolveExit);
});
assert.equal(await invokeSecond([]), 0);
assert.equal(isAlive(primary.pid), true, 'Second launch closed the existing app.');
assert.equal(await invokeSecond(['--quit']), 0);
assert.equal(await primaryExit, 0);
const quitReport = JSON.parse(await readFile(join(quitFixture, 'lifecycle-report.json'), 'utf8'));
assert.equal(quitReport.secondInstances, 2);
assert.equal(quitReport.quitRequested, true);
assert.equal(quitReport.serverClosed, true);
await assert.rejects(fetch(`http://127.0.0.1:${quitReport.port}/health`, { signal: AbortSignal.timeout(1000) }));
for (let attempt = 0; attempt < 20 && quitReport.ownedProcessIds.some(isAlive); attempt++) await new Promise(resolveWait => setTimeout(resolveWait, 100));
assert.deepEqual(quitReport.ownedProcessIds.filter(isAlive), []);
console.log('PASS: second launch reused the existing app; Quit stopped the server and app processes.');
await rm(quitFixture, { recursive: true });
