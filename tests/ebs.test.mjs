import test from 'node:test';
import assert from 'node:assert/strict';
import { randomBytes } from 'node:crypto';
import { mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { once } from 'node:events';
import { createEbs } from '../server/ebs.mjs';
import { signJwt } from '../server/auth.mjs';
import { demoSnapshot } from '../server/demo.mjs';

test('full pairing, publishing, Twitch authentication, channel isolation and code reuse', async t => {
  const directory = await mkdtemp(join(tmpdir(), 'spam-twitch-test-'));
  const secret = randomBytes(32);
  const notifications = [];
  const archiveBytes = Buffer.from('PK\x03\x04download-test');
  await writeFile(join(directory, 'SPAM-Twitch-Companion-0.1.0.zip'), archiveBytes);
  const installerBytes = Buffer.from('MZinstaller-fixture');
  await writeFile(join(directory, 'SPAM-Twitch-Setup-0.1.0.exe'), installerBytes);
  const { server } = await createEbs({ secret, clientId: 'testextension', downloadDirectory: directory, dataPath: join(directory, 'state.json'), fetch: async (url, request) => { notifications.push({ url, request }); return { ok: true }; } });
  server.listen(0, '127.0.0.1'); await once(server, 'listening');
  t.after(async () => { await new Promise(resolve => server.close(resolve)); await rm(directory, { recursive: true, force: true }); });
  const base = `http://127.0.0.1:${server.address().port}`;
  const homepage = await fetch(base + '/');
  assert.equal(homepage.status, 200);
  assert.match(homepage.headers.get('content-type'), /text\/html/);
  assert.match(await homepage.text(), /SPAM Card Inspector/);
  assert.equal((await fetch(base + '/style.css')).status, 200);
  assert.equal((await fetch(base + '/privacy.html')).status, 200);
  assert.equal((await fetch(base + '/terms.html')).status, 200);
  const download = await fetch(base + '/downloads/SPAM-Twitch-Companion-0.1.0.zip');
  assert.equal(download.headers.get('content-type'), 'application/zip');
  assert.match(download.headers.get('content-disposition'), /^attachment; filename="SPAM/);
  assert.deepEqual(Buffer.from(await download.arrayBuffer()), archiveBytes);
  const downloadHead = await fetch(base + '/downloads/SPAM-Twitch-Companion-0.1.0.zip', { method: 'HEAD' });
  assert.equal(downloadHead.status, 200);
  assert.equal(downloadHead.headers.get('content-length'), String(archiveBytes.length));
  assert.equal((await downloadHead.arrayBuffer()).byteLength, 0);
  assert.equal((await fetch(base + '/downloads/credentials.json')).status, 404);
  assert.equal((await fetch(base + '/downloads/missing.zip')).status, 404);
  const installer = await fetch(base + '/downloads/SPAM-Twitch-Setup-0.1.0.exe');
  assert.equal(installer.status, 200);
  assert.match(installer.headers.get('content-disposition'), /SPAM-Twitch-Setup-0.1.0.exe/);
  assert.deepEqual(Buffer.from(await installer.arrayBuffer()), installerBytes);
  assert.equal((await fetch(base + '/downloads/unins000.exe')).status, 404);
  const broadcaster = signJwt({ role: 'broadcaster', channel_id: '123', exp: Math.floor(Date.now() / 1000) + 60 }, secret);
  const viewer = signJwt({ role: 'viewer', channel_id: '123', exp: Math.floor(Date.now() / 1000) + 60 }, secret);
  const otherViewer = signJwt({ role: 'viewer', channel_id: '456', exp: Math.floor(Date.now() / 1000) + 60 }, secret);
  const call = (path, method, token, input, headers = {}) => fetch(base + path, { method, headers: { Authorization: `Bearer ${token}`, 'Content-Type': 'application/json', ...headers }, body: input === undefined ? undefined : JSON.stringify(input) });
  assert.equal((await call('/api/pair-code', 'POST', viewer, {})).status, 401);
  const issued = await call('/api/pair-code', 'POST', broadcaster, {}); assert.equal(issued.status, 200);
  const { code } = await issued.json();
  const paired = await call('/api/pair', 'POST', '', { code }); assert.equal(paired.status, 200);
  const { publisherToken, channelId } = await paired.json(); assert.equal(channelId, '123');
  assert.equal((await call('/api/pair', 'POST', '', { code })).status, 401);
  const snapshot = { ...demoSnapshot(), source: 'game' };
  assert.equal((await call('/api/publish', 'POST', 'incorrect', snapshot, { 'x-channel-id': '123' })).status, 401);
  assert.equal((await call('/api/publish', 'POST', publisherToken, snapshot, { 'x-channel-id': '456' })).status, 401);
  const published = await call('/api/publish', 'POST', publisherToken, snapshot, { 'x-channel-id': '123' }); assert.equal(published.status, 200);
  assert.equal(notifications.length, 1);
  const notificationClaims = JSON.parse(Buffer.from(notifications[0].request.headers.Authorization.split('.')[1], 'base64url').toString());
  assert.equal(notificationClaims.user_id, '123'); assert.equal(notificationClaims.channel_id, '123');
  const received = await call('/api/state', 'GET', viewer); const state = await received.json();
  assert.equal(state.frames.at(-1).cards.length, 3);
  assert.equal((await (await call('/api/state', 'GET', otherViewer)).json()).frames.length, 0);
  assert.equal((await call('/api/state', 'GET', '')).status, 401);
  assert.equal((await call('/api/layout', 'PUT', viewer, {})).status, 401);
  assert.equal((await call('/api/layout', 'PUT', broadcaster, { x: .1, w: .8 })).status, 200);
  assert.equal((await call('/api/layout', 'PUT', broadcaster, { x: .9, w: .8 })).status, 400);
  assert.equal((await call('/api/state', 'GET', viewer, undefined, { Origin: 'https://evil.example' })).status, 403);
  const cors = await call('/api/state', 'GET', viewer, undefined, { Origin: 'https://testextension.ext-twitch.tv' });
  assert.equal(cors.headers.get('Access-Control-Allow-Origin'), 'https://testextension.ext-twitch.tv');
  const rotation = await (await call('/api/pair-code', 'POST', broadcaster, {})).json();
  await call('/api/pair', 'POST', '', { code: rotation.code });
  assert.equal((await call('/api/publish', 'POST', publisherToken, snapshot, { 'x-channel-id': '123' })).status, 401);
});
